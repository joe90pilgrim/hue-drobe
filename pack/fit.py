"""Default-fit garment sizes from a body's tape measurements (MVP-03). Pure Python; no Blender needed.

The output has the same shape as the flat garment measurements the spike's body_from_measurements.py reads, so the
spike's fitting and checks run unchanged. The ease values and proportions live in fit_config.json.
"""


import hashlib, json


def config_hash(cfg):
    """SHA-256 of the fit config's content (key order and whitespace do not matter). Stamped into every report by build_pack.py."""
    return hashlib.sha256(json.dumps(cfg, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def merge(base, over):
    """V2-03: a person's fit is the shared fit_config.json with that person's overrides from fit_people.json laid over it.
    Nested objects merge key by key; any other value replaces the default. Keys starting with '_' (notes) are ignored."""
    out = dict(base)
    for k, v in over.items():
        if k.startswith("_"):
            continue
        out[k] = merge(base[k], v) if isinstance(v, dict) and isinstance(base.get(k), dict) else v
    return out


def _r(x):
    return round(x, 1)


def default_garments(m, cfg):
    """m: measurements dict (height_cm, chest_cm, waist_cm, hips_cm, optional inside_leg_cm). Returns {'tee':..., 'trousers':..., 'sweatshirt':..., 'shorts':...}."""
    for key in ("height_cm", "chest_cm", "waist_cm", "hips_cm"):
        if key not in m:
            raise KeyError(f"measurements are missing {key}")
    height = m["height_cm"]
    t, r = cfg["tee"], cfg["trousers"]
    colour = list(cfg["colour_srgb"])

    trousers_hip = m["hips_cm"] + r["hip_ease_cm"]
    inside_leg = m.get("inside_leg_cm", r["inside_leg_fraction_of_height"] * height)
    trousers = {
        # Trousers sit below the natural waist, where the body is wider: start from the tape waist and move part of the way to the hips
        "waist_circ_cm": _r(m["waist_cm"] + r["waist_towards_hips_fraction"] * (m["hips_cm"] - m["waist_cm"]) + r["waist_ease_cm"]),
        "hip_circ_cm": _r(trousers_hip),
        "rise_cm": _r(r["rise_fraction_of_height"] * height),
        "inseam_cm": _r(inside_leg - r["hem_above_floor_cm"]),
        "leg_opening_circ_cm": _r(r["leg_opening_fraction_of_hip"] * trousers_hip),
        "colour_srgb": colour,
    }

    tee_chest = m["chest_cm"] + t["chest_ease_cm"]
    tee = {
        "chest_circ_cm": _r(tee_chest),
        # No hem_circ_cm on purpose: there is no real item to compare with. The shell method cannot make a loose tee at the
        # waist (known limit B22), and the checker skips the tee-circumference comparison when this key is absent.
        "length_cm": _r(t["length_fraction_of_height"] * height),
        "sleeve_cm": _r(t["sleeve_fraction_of_height"] * height),
        "neckline_width_cm": _r(t["neckline_width_fraction_of_height"] * height),
        "neckline_drop_front_cm": t["neckline_drop_front_cm"],
        # V1.1-04: the other necklines, each with its own width and depth (the width is a multiple of the crew neck's)
        "necklines": {name: {"drop_front_cm": n["drop_front_cm"],
                             "neckline_width_cm": _r(n["width_factor"] * t["neckline_width_fraction_of_height"] * height)}
                      for name, n in t.get("necklines", {}).items()},
        "colour_srgb": colour,
    }
    s = cfg["sweatshirt"]
    sweatshirt = {
        "chest_circ_cm": _r(m["chest_cm"] + s["chest_ease_cm"]),
        "hem_above_crotch_cm": s["hem_above_crotch_cm"],
        "cuff_above_wrist_cm": s["cuff_above_wrist_cm"],
        "neckline_width_cm": _r(s["neckline_width_fraction_of_height"] * height),
        "neckline_drop_front_cm": s["neckline_drop_front_cm"],
        "forearm_ease_fraction": s["forearm_ease_fraction"],
        "rib_band_cm": s["rib_band_cm"],
        "hem_rib_gap_cm": s["hem_rib_gap_cm"],
        "cuff_rib_gap_cm": s["cuff_rib_gap_cm"],
        "colour_srgb": colour,
    }
    out = {"_note": "Generated by pack/fit.py from the body's measurements and pack/fit_config.json. Do not edit.",
           "tee": tee, "trousers": trousers, "sweatshirt": sweatshirt}
    if "shirt" in cfg:  # V3-03: the collared shirt in three sleeve lengths; the tee's shell with a point collar and a raised placket
        sh = cfg["shirt"]
        out["shirt"] = {
            "chest_circ_cm": _r(m["chest_cm"] + sh["chest_ease_cm"]),
            "length_cm": _r(sh["length_fraction_of_height"] * height),
            "sleeve_short_cm": _r(sh["sleeve_short_fraction_of_height"] * height),
            "sleeve_mid_cm": _r(sh["sleeve_mid_fraction_of_height"] * height),
            "cuff_above_wrist_cm": sh["cuff_above_wrist_cm"],
            "forearm_ease_fraction": sh["forearm_ease_fraction"],
            "cuff_band_cm": sh["cuff_band_cm"],
            "cuff_gap_cm": sh["cuff_gap_cm"],
            "neckline_width_cm": _r(sh["neckline_width_fraction_of_height"] * height),
            "neckline_drop_front_cm": sh["neckline_drop_front_cm"],
            "detail": {**sh["collar"], **{"placket_" + k: v for k, v in sh["placket"].items()}, **sh["shade"]},
            "colour_srgb": colour,
        }
    if "shorts" in cfg:  # V1.1-05: sizes taken from the trousers on the body, so only the length and the extra opening are set here
        h = cfg["shorts"]
        out["shorts"] = {"inseam_cm": h["inseam_cm"], "leg_opening_extra_cm": h["leg_opening_extra_cm"],
                         "flare_band_cm": h["flare_band_cm"], "colour_srgb": colour}
    if "tights" in cfg:  # V2-04: the gap and the hem height are all the generator needs; the shell is the trousers' template
        t_ = cfg["tights"]
        out["tights"] = {"gap_cm": t_["gap_cm"], "hem_above_floor_cm": t_["hem_above_floor_cm"],
                         "waist_below_trousers_cm": t_["waist_below_trousers_cm"],
                         "smooth_iterations": t_["smooth_iterations"], "colour_srgb": colour}
    if "shading" in cfg:  # V3-03 follow-up: shading normals averaged over this radius for every offset-shell garment but the tights
        out["shading_radius_cm"] = cfg["shading"]["radius_cm"]
    if "bust" in cfg:  # V2-08: how the tops sit over the bust; the generator applies it on female bodies only
        b_ = cfg["bust"]
        out["bust"] = {k: b_[k] for k in ("hang_reach_cm", "hang_slack_cm_per_cm", "hang_halfwidth_cm", "hang_side_taper_cm_per_cm", "pad_cm", "pad_radius_cm", "tee_trousers_gap_cm")}
    return out
